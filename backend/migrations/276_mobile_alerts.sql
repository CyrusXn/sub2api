CREATE TABLE mobile_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL CHECK (kind IN ('low_balance', 'multiplier_changed', 'upstream_balance_empty')),
    title TEXT NOT NULL,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE mobile_balance_alert_states (
    identity_key TEXT PRIMARY KEY,
    snapshot_id BIGINT NOT NULL DEFAULT 0,
    low_balance_active BOOLEAN NOT NULL DEFAULT FALSE,
    low_balance_threshold DOUBLE PRECISION,
    multiplier_baseline DOUBLE PRECISION
);

-- 串行分配事件 ID，使手机按游标读取时不会跳过先分配 ID、后提交的事件。
CREATE FUNCTION append_mobile_alert(event_kind TEXT, event_title TEXT, event_body TEXT)
RETURNS VOID LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_advisory_xact_lock(20914, 276);
    INSERT INTO mobile_alerts (kind, title, body) VALUES (event_kind, event_title, event_body);
END;
$$;

CREATE FUNCTION capture_mobile_ops_balance_alert()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    PERFORM append_mobile_alert('upstream_balance_empty', '上游余额不足',
        COALESCE(NULLIF(regexp_replace(NEW.title, '异常$', ''), ''),
                 '账号 #' || (NEW.dimensions ->> 'account_id')) || '，上游调用因余额不足失败');
    RETURN NEW;
END;
$$;

CREATE TRIGGER capture_mobile_ops_balance_alert
AFTER INSERT ON ops_alert_events
FOR EACH ROW WHEN (NEW.dimensions ->> 'diagnosis' = 'balance' AND NEW.dimensions ? 'account_id')
EXECUTE FUNCTION capture_mobile_ops_balance_alert();

-- 首次安装补入近期已发生的余额耗尽事件，让已出问题的账号不必等下一次请求失败。
INSERT INTO mobile_alerts (kind, title, body, created_at)
SELECT 'upstream_balance_empty', '上游余额不足',
       COALESCE(NULLIF(regexp_replace(latest.title, '异常$', ''), ''),
                '账号 #' || (latest.dimensions ->> 'account_id')) || '，上游调用因余额不足失败',
       latest.fired_at
FROM (
    SELECT DISTINCT ON (dimensions ->> 'account_id') title, dimensions, fired_at, id
    FROM ops_alert_events
    WHERE fired_at >= now() - interval '24 hours'
      AND dimensions ->> 'diagnosis' = 'balance'
      AND dimensions ->> 'account_id' IS NOT NULL
    ORDER BY dimensions ->> 'account_id', fired_at DESC, id DESC
) latest
ORDER BY latest.fired_at, latest.id;

-- 使用已采集的倍率作为基线，并对最近仍低于阈值的账号补发一次。
WITH threshold AS (
    SELECT COALESCE((SELECT CASE WHEN value ~ '^[0-9]{1,20}(\.[0-9]{1,20})?$'
                                 THEN value::double precision END
                     FROM settings WHERE key = 'balance_center_low_balance_threshold'), 5) AS amount
), latest AS (
    SELECT cs.identity_key, cs.snapshot_id, cs.rate_multiplier, cs.converted_balance, cs.account_id,
           cs.probed_at >= now() - interval '24 hours' AND cs.converted_balance < t.amount AS is_low,
           t.amount AS threshold
    FROM balance_center_current_states cs CROSS JOIN threshold t
    WHERE cs.account_id IS NOT NULL OR cs.legacy_key_id IS NOT NULL
), seeded AS (
    INSERT INTO mobile_balance_alert_states (identity_key, snapshot_id, low_balance_active, low_balance_threshold, multiplier_baseline)
    SELECT identity_key, snapshot_id, COALESCE(is_low, FALSE), CASE WHEN is_low THEN threshold END, rate_multiplier
    FROM latest
    RETURNING identity_key, low_balance_active
)
INSERT INTO mobile_alerts (kind, title, body)
SELECT 'low_balance', '余额不足',
       '账号 #' || COALESCE(latest.account_id::text, replace(latest.identity_key, 'legacy:', '历史账号 ')) || '，最近记录余额 '
       || latest.converted_balance || ' 元，提醒阈值 ' || latest.threshold || ' 元'
FROM latest JOIN seeded USING (identity_key)
WHERE seeded.low_balance_active
ORDER BY latest.snapshot_id;
